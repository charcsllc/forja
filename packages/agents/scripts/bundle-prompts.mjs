/**
 * Bundles the agent prompts into `src/prompts/bundle.generated.ts`.
 *
 * What this protects: `docs/prompts/**` is the single source of the prompts
 * (docs/prompts/README.md) and the engine never reads `docs/` at runtime. The prompts
 * travel inside the engine bundle as string constants, so the Docker image needs no copy
 * of `docs/` and a prompt edit is a reviewed code change. `src/context/*.md` (reference
 * sheets such as Next.js 16) are bundled the same way.
 *
 *   node scripts/bundle-prompts.mjs          regenerate
 *   node scripts/bundle-prompts.mjs --check  exit 1 when the bundle is stale (tests call it)
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const pkg = fileURLToPath(new URL("..", import.meta.url));
const promptsDir = path.join(pkg, "..", "..", "docs", "prompts");
const contextDir = path.join(pkg, "src", "context");
const outFile = path.join(pkg, "src", "prompts", "bundle.generated.ts");

async function mdFiles(dir) {
  const names = (await readdir(dir)).filter((n) => n.endsWith(".md")).sort();
  const out = {};
  for (const name of names) out[name.slice(0, -3)] = (await readFile(path.join(dir, name), "utf8")).replace(/\r\n/g, "\n");
  return out;
}

export async function render() {
  const bundle = {
    base: (await readFile(path.join(promptsDir, "_base-engineer.md"), "utf8")).replace(/\r\n/g, "\n"),
    roles: await mdFiles(path.join(promptsDir, "roles")),
    providers: await mdFiles(path.join(promptsDir, "providers")),
    context: await mdFiles(contextDir),
  };
  const json = JSON.stringify(bundle, null, 2);
  const hash = createHash("sha256").update(json).digest("hex").slice(0, 16);
  return [
    "/**",
    " * GENERATED by `npm run prompts:bundle -w @forja/agents` from docs/prompts/** and",
    " * packages/agents/src/context/*.md. Do not edit: change the Markdown and regenerate.",
    " * A test fails when this file is stale.",
    " */",
    `export const PROMPT_BUNDLE_HASH = ${JSON.stringify(hash)};`,
    "",
    `export const PROMPT_BUNDLE: {`,
    "  readonly base: string;",
    "  readonly roles: Readonly<Record<string, string>>;",
    "  readonly providers: Readonly<Record<string, string>>;",
    "  readonly context: Readonly<Record<string, string>>;",
    `} = ${json};`,
    "",
  ].join("\n");
}

const check = process.argv.includes("--check");
const next = await render();
const current = await readFile(outFile, "utf8").catch(() => "");
if (check) {
  if (current !== next) {
    console.error("src/prompts/bundle.generated.ts is stale: run `npm run prompts:bundle -w @forja/agents`.");
    process.exit(1);
  }
  console.log("prompt bundle is up to date");
} else if (current !== next) {
  await writeFile(outFile, next);
  console.log(`wrote ${path.relative(pkg, outFile)}`);
} else {
  console.log("prompt bundle already up to date");
}
